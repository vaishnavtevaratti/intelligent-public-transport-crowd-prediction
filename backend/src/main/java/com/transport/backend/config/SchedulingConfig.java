/** Background jobs (simulation, scheduled predictions, cleanup). Disabled in automated tests. */
@Configuration
@EnableScheduling
@ConditionalOnProperty(name = "app.scheduling.enabled", havingValue = "true", matchIfMissing = true)
public class SchedulingConfig {
}
