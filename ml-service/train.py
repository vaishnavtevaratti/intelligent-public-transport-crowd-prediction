"""Train, evaluate and save the crowd-level classifier.

Steps
  1. Load data/crowd_history.csv (run generate_dataset.py first if it is missing).
  2. Build features (features.py) and the LOW/MEDIUM/HIGH target.
  3. Time-based split: the last 20 % of days are held out as the test set, so the
     model is always evaluated on days it never saw (no leakage between
     trips of the same day).
  4. Compare three candidate models with 5-fold cross-validation on the
     training days only, using macro-F1 (classes are imbalanced, so accuracy
     alone would favour always predicting LOW).
  5. Refit the best candidate on all training days, evaluate once on the test
     days, and save the pipeline + metrics.

Usage:  python train.py
Outputs: models/crowd_model.joblib, models/metrics.json
"""

import json
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score
from sklearn.model_selection import GroupKFold, cross_val_score
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from features import CLASSES, MODEL_FEATURES, add_derived_features

BASE = Path(__file__).parent
DATA = BASE / "data" / "crowd_history.csv"
MODEL_PATH = BASE / "models" / "crowd_model.joblib"
METRICS_PATH = BASE / "models" / "metrics.json"
RANDOM_STATE = 42


def candidates():
    return {
        "logistic_regression": Pipeline([
            ("impute", SimpleImputer(strategy="median")),
            ("scale", StandardScaler()),
            ("model", LogisticRegression(max_iter=2000, class_weight="balanced")),
        ]),
        "random_forest": Pipeline([
            ("impute", SimpleImputer(strategy="median")),
            ("model", RandomForestClassifier(n_estimators=150, max_depth=14, min_samples_leaf=5,
                                             class_weight="balanced", n_jobs=-1,
                                             random_state=RANDOM_STATE)),
        ]),
        "hist_gradient_boosting": Pipeline([
            ("impute", SimpleImputer(strategy="median")),
            ("model", HistGradientBoostingClassifier(max_iter=300, learning_rate=0.08,
                                                     class_weight="balanced",
                                                     random_state=RANDOM_STATE)),
        ]),
    }


def main():
    if not DATA.exists():
        raise SystemExit(f"{DATA} not found. Run: python generate_dataset.py")

    df = pd.read_csv(DATA)
    df = df[df["crowd_level"].isin(CLASSES)].reset_index(drop=True)
    X = add_derived_features(df)
    y = df["crowd_level"]

    # --- time-based train/test split (by day) ---
    days = np.sort(df["trip_date"].unique())
    cutoff = days[int(len(days) * 0.8)]
    train_mask = df["trip_date"] < cutoff
    X_train, y_train, groups = X[train_mask], y[train_mask], df.loc[train_mask, "trip_date"]
    X_test, y_test = X[~train_mask], y[~train_mask]
    print(f"Train: {len(X_train)} trips ({train_mask.sum()} rows, days < {cutoff}); "
          f"Test: {len(X_test)} trips (days >= {cutoff})")

    # --- model selection with grouped CV (groups = days, no day split across folds) ---
    cv_scores = {}
    for name, pipe in candidates().items():
        scores = cross_val_score(pipe, X_train, y_train, groups=groups,
                                 cv=GroupKFold(n_splits=5), scoring="f1_macro", n_jobs=1)
        cv_scores[name] = {"mean": float(scores.mean()), "std": float(scores.std())}
        print(f"  {name:24s} CV macro-F1 = {scores.mean():.4f} ± {scores.std():.4f}")

    best_name = max(cv_scores, key=lambda n: cv_scores[n]["mean"])
    print(f"Selected model: {best_name}")

    best = candidates()[best_name]
    best.fit(X_train, y_train)
    y_pred = best.predict(X_test)

    labels = CLASSES
    report = classification_report(y_test, y_pred, labels=labels, output_dict=True, zero_division=0)
    metrics = {
        "model_version": f"{best_name}-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}",
        "model_type": best_name,
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "sklearn_version": sklearn.__version__,
        "dataset": {
            "path": "data/crowd_history.csv",
            "source": "SYNTHETIC - generated by generate_dataset.py (not real passenger data)",
            "rows": int(len(df)),
            "train_rows": int(len(X_train)),
            "test_rows": int(len(X_test)),
            "split": f"time-based: train days < {cutoff}, test days >= {cutoff}",
            "class_distribution": {k: int(v) for k, v in y.value_counts().items()},
        },
        "features": MODEL_FEATURES,
        "classes": labels,
        "cross_validation_macro_f1": cv_scores,
        "test": {
            "accuracy": float(accuracy_score(y_test, y_pred)),
            "macro_f1": float(f1_score(y_test, y_pred, average="macro")),
            "per_class": {c: {k: float(report[c][k]) for k in ("precision", "recall", "f1-score", "support")}
                          for c in labels},
            "confusion_matrix": {"labels": labels,
                                 "matrix": confusion_matrix(y_test, y_pred, labels=labels).tolist()},
        },
    }

    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"pipeline": best, "metrics": metrics}, MODEL_PATH)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2))

    print(f"\nTest accuracy : {metrics['test']['accuracy']:.4f}")
    print(f"Test macro-F1 : {metrics['test']['macro_f1']:.4f}")
    print(classification_report(y_test, y_pred, labels=labels, zero_division=0))
    print("Confusion matrix (rows = actual, cols = predicted):", labels)
    print(np.array(metrics["test"]["confusion_matrix"]["matrix"]))
    print(f"\nSaved model to {MODEL_PATH}")


if __name__ == "__main__":
    main()
